def parse_topics(text, count):
    out = []
    seen = set()
    for line in (text or "").splitlines():
        line = re.sub(r"^[\-\*\d\.\)\s\"'·•]+", "", line.strip()).strip().strip('"').strip()
        key = re.sub(r"\s+", "", line)
        if line and key not in seen:
            seen.add(key)
            out.append({"keyword": line, "news": []})
        if len(out) >= count:
            break
    return out
