def split_by_lane(items, want, other_pool=None):
    """판별 결과(lane_ai)가 want('long'/'season')인 것 우선, 부족하면 나머지로 채움."""
    match = [x for x in items if x.get("lane_ai") == want]
    rest = [x for x in items if x.get("lane_ai") != want]
    return match, rest


